@app.route("/register", methods=["GET", "POST"])
def register():
    if session.get("user_id"):
        return redirect("/")
    if request.method in ("GET", "HEAD"):
        return render_template("register.html")
    else:       
        username = request.form.get("username")
        password = request.form.get("password")
        confirmation = request.form.get("confirmation")

        if not username:
            flash("Username entered is invalid.")
            return redirect("/register")

        if not password:
            flash("Password entered is invalid.")
            return redirect("/register")

        if not confirmation or password != confirmation:
            flash("Password and confirmation do not match!")
            return redirect("/register")

        conn = get_db_connection()

        try:
            user = conn.execute(
                "SELECT id FROM users WHERE username = %s",
                (username,)
            ).fetchone()

            if user:
                flash("Username already exists.")
                return redirect("/register")

            password_hash = generate_password_hash(password)

            user = conn.execute(
                """
                INSERT INTO users (username, password_hash)
                VALUES (%s, %s)
                RETURNING id
                """,
                (username, password_hash)
            ).fetchone()

            conn.commit()

            session["user_id"] = user["id"]

            return redirect("/")

        finally:
            conn.close()

@app.route("/games")
@login_required
def games():
    season = request.args.get(
        "season",
        default=helpers.current_nfl_season(),
        type = int
    )

    week = request.args.get("week", type=int)

    if week is None:
        if season == helpers.current_nfl_season():
            week = helpers.get_current_nfl_week(season)
        else:
            week = 1

    if season < 1920 or season > helpers.current_nfl_season():
        abort(404)

    if not 1 <= week <= 18:
        abort(404)

    data = helpers.get_scoreboard(season,week)

    games=[]

    for event in data["events"]:
        competitors = event["competitions"][0]["competitors"]
        game = {
            "id": event["id"],
            "name": event["name"],
            "date": event["date"],
            "status": event["status"]["type"]["detail"],
            "state": event["status"]["type"]["state"],
            "locked": helpers.is_game_locked(event)
        }

        for competitor in competitors:
            team = competitor["team"]
            records = competitor.get("records", [])
            
            team_data = {
                "name": team["displayName"],
                "short_name": team["shortDisplayName"],
                "logo": team.get("logo"),
                "id": competitor["id"],
                "record": records[0]["summary"] if records else "N/A",
                "score": competitor.get("score", "0"),
                "color": team.get("color", "1a1a1a"),
                "alternate_color": team.get("alternateColor", "ffffff")
            }  
            if competitor["homeAway"] == "home":
                game["home"] = team_data
            else:
                game["away"] = team_data

        games.append(game)

    conn = get_db_connection()
    try:
        picks = conn.execute("SELECT game_id, picked_team FROM PICKS WHERE user_id = %s", (session["user_id"],)).fetchall()
    finally:
        conn.close()
    user_picks = {pick["game_id"]: pick["picked_team"] for pick in picks}
    return render_template("games.html",games=games,week=week,season=season,user_picks=user_picks)

    
@app.route("/pick", methods = ["POST"])
@login_required
def pick():
    data = request.get_json()

    if data is None:
        return jsonify({"error": "Invalid request"}), 400

    if not data.get("game_id") or not data.get("team_id"):
        return jsonify({"error": "Missing team or game id"}), 400
    
    game_id = data["game_id"]
    team_id = data["team_id"]
    user_id = session["user_id"]
    try:
        response = requests.get(
            f"https://sports.core.api.espn.com/v2/sports/football/leagues/nfl/events/{game_id}",
            timeout=10
        )
        response.raise_for_status()
        event = response.json()
    except requests.RequestException:
        return jsonify({"error": "Unable to verify game with ESPN"}), 503

    if helpers.is_game_locked(event):
       return jsonify({"error": "Picks are locked"}), 403

    competitors = event["competitions"][0]["competitors"]
    if team_id not in [team["id"] for team in competitors]:
        return jsonify({"error": "Invalid team"}), 403
    


    conn = get_db_connection()
    try:
        conn.execute(
            """
            INSERT INTO picks (user_id, game_id, picked_team)
            VALUES (%s, %s, %s)
            ON CONFLICT (user_id, game_id)
            DO UPDATE SET picked_team = EXCLUDED.picked_team
            """,
            (user_id,game_id,team_id)
        )

        conn.commit()
    finally:
        conn.close()

    return jsonify({"success": True}), 200



@app.route("/community-picks")
@login_required
def community_picks():

    season = helpers.current_nfl_season()
    week = helpers.get_current_nfl_week(season)
    data = helpers.get_scoreboard(season, week)
    events = data["events"]

    game_ids = [event["id"] for event in events]

    conn = get_db_connection()

    try:
        users = conn.execute(
            "SELECT id, username FROM users ORDER BY username"
        ).fetchall()

        picks = conn.execute(
            """
            SELECT user_id, game_id, picked_team
            FROM picks
            WHERE game_id = ANY(%s)
            """,
            (game_ids,)
        ).fetchall()

    finally:
        conn.close()

    picks_by_game = {}

    for pick in picks:
        game_id = str(pick["game_id"])
        user_id = pick["user_id"]

        picks_by_game.setdefault(game_id, {})
        picks_by_game[game_id][user_id] = str(pick["picked_team"])

    games = []

    for event in events:
        game_id = str(event["id"])
        competitors = event["competitions"][0]["competitors"]

        teams = {}

        for competitor in competitors:
            team = competitor["team"]
            teams[str(competitor["id"])] = team["displayName"]

        locked = helpers.is_game_locked(event)

        game = {
            "id": game_id,
            "name": event["name"],
            "date": event["date"],
            "status": event["status"]["type"]["detail"],
            "locked": locked,
            "picks": {}
        }

        for user in users:
            user_id = user["id"]
            username = user["username"]

            if not locked:
                game["picks"][username] = "Hidden"
            else:
                picked_team = picks_by_game.get(game_id, {}).get(user_id)

                if picked_team:
                    game["picks"][username] = teams.get(
                        picked_team,
                        "Invalid pick"
                    )
                else:
                    game["picks"][username] = "No pick"

        games.append(game)

    return render_template(
        "community_picks.html",
        games=games,
        users=users,
        week=week,
        season=season
    )


