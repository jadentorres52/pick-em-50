def index():
    return redirect("/games")


@app.route('/login', methods=['GET', 'POST'])
def login():
    if request.method == 'GET':
        return render_template('login.html')
    else:
        username = request.form.get("username")
        if not username:
            flash("Username entered is invalid.")
            return redirect("/login")
        
        password = request.form.get("password")
        if not password:
            flash("Password entered is invalid.")
            return redirect("/login")

        conn = get_db_connection()
        user = conn.execute("SELECT id, username, password_hash FROM users WHERE username = %s", (username,)).fetchone()
        if not user:
            flash("Username does not exist. Did you mean to register?")
            conn.close()
            return redirect("/login")

        if check_password_hash(user['password_hash'], password):
            session["user_id"] = user['id']
            conn.close()
            return redirect('/')
        else:
            flash('Password did not match.')
            conn.close()
            return redirect('/login')



@app.route("/logout")
def logout():
    session.clear()
    return redirect("/login")

@app.route("/register", methods=["GET", "POST"])
def register():
    if request.method == "GET":
        return render_template("register.html")

    username = request.form.get("username")
    password = request.form.get("password")
    confirmation = request.form.get("confirmation")

    if not username:
        flash("Username entered is invalid.")
        return redirect("/register")

    if not password:
        flash("Password entered is invalid.")
        return redirect("/register")

    if not confirmation or password != confirmation:
        flash("Password and confirmation do not match!")
        return redirect("/register")

    conn = get_db_connection()

    try:
        user = conn.execute(
            "SELECT id FROM users WHERE username = %s",
            (username,)
        ).fetchone()

        if user:
            flash("Username already exists.")
            return redirect("/register")

        password_hash = generate_password_hash(password)

        user = conn.execute(
            """
            INSERT INTO users (username, password_hash)
            VALUES (%s, %s)
            RETURNING id
            """,
            (username, password_hash)
        ).fetchone()

        conn.commit()

        session["user_id"] = user["id"]

        return redirect("/")

    finally:
        conn.close()

@app.route("/games")
@login_required
def games():
    season = request.args.get(
        "season",
        default=helpers.current_nfl_season(),
        type = int
    )

    week = request.args.get("week", type=int)

    if week is None:
        if season == helpers.current_nfl_season():
            week = helpers.get_current_nfl_week(season)
        else:
            week = 1

    if season < 1920 or season > helpers.current_nfl_season():
        abort(404)

    if not 1 <= week <= 18:
        abort(404)

    data = helpers.get_scoreboard(season,week)

    games=[]
    now = datetime.now(timezone.utc)

    for event in data["events"]:
        competitors = event["competitions"][0]["competitors"]
        game = {
            "id": event["id"],
            "name": event["name"],
            "date": event["date"],
            "status": event["status"]["type"]["detail"],
            "state": event["status"]["type"]["state"],
            "locked": helpers.is_game_locked(event, now)
        }

        for competitor in competitors:
            team = competitor["team"]
            records = competitor.get("records", [])
            
            team_data = {
                "name": team["displayName"],
                "logo": team.get("logo"),
                "record": records[0]["summary"] if records else "N/A",
                "score": competitor.get("score", "0"),
                "color": team.get("color", "1a1a1a"),
                "alternate_color": team.get("alternateColor", "ffffff")
                
            }  
            print(team["displayName"], team.get("color"), team.get("alternateColor"))

            if competitor["homeAway"] == "home":
                game["home"] = team_data
            else:
                game["away"] = team_data

        games.append(game)
    return render_template("games.html",games=games,week=week,season=season)

    



